/**
 ******************************************************************************
 * @file    touch_conf.h
 * @brief   电阻触摸屏驱动板级配置 — 移植到新板/新屏时只需修改本文件
 *
 * 使用说明:
 *   1. 本文件由 touch.h 自动包含, 无需手动 include
 *   2. 修改本文件后, 若与 touch.h 版本不匹配会触发编译期 #error
 *   3. 所有宏取值均与迁移前的驱动定义保持一致 (仅位置变化)
 *
 * 移植清单:
 *   - 触摸引脚:      TP_*_GPIO / TP_*_PIN (软件模拟 SPI)
 *   - 校准方式:      TP_CAL_PRESET_ENABLE (新屏设为 0, 走四角校准)
 *   - 采样滤波:      TP_READ_TIMES / TP_LOST_VAL / TP_ERR_RANGE / TP_READ_MIN
 ******************************************************************************
 */
#ifndef __TOUCH_CONF_H
#define __TOUCH_CONF_H

/** 配置版本号: 与 touch.h 中 TOUCH_CONF_VER_EXPECT 匹配, 不一致时编译报错 */
#define TOUCH_CONF_VER      0x0101

/* ========================================================================= */
/*  触摸引脚 (软件模拟 SPI)                                                    */
/* ========================================================================= */
#define TP_PEN_GPIO     GPIOC
#define TP_PEN_PIN      GPIO_PIN_5
#define TP_MISO_GPIO    GPIOB
#define TP_MISO_PIN     GPIO_PIN_14
#define TP_MOSI_GPIO    GPIOB
#define TP_MOSI_PIN     GPIO_PIN_15
#define TP_SCK_GPIO     GPIOB
#define TP_SCK_PIN      GPIO_PIN_13
#define TP_CS_GPIO      GPIOB
#define TP_CS_PIN       GPIO_PIN_12

/* ========================================================================= */
/*  校准                                                                      */
/* ========================================================================= */
/**
 * 是否使用预存校准值:
 *   1 = 使用 TP_PRESET_CAL 预存参数, 跳过四角校准 (当前屏幕已验证可用)
 *   0 = 新屏/换模组: 关闭预存, 上电后调用 TP_Adjust() 重新四角校准
 */
#define TP_CAL_PRESET_ENABLE    1

/** 预存四角校准原始值: 左上(20,20), 右上(220,20), 左下(20,300), 右下(220,300) */
#if (TP_CAL_PRESET_ENABLE == 1)
static const u16 TP_PRESET_CAL[4][2] = {
    {548, 302}, {3555, 404}, {443, 3606}, {3239, 3675},
};
#endif

/* ========================================================================= */
/*  采样滤波参数                                                              */
/* ========================================================================= */
#define TP_READ_TIMES   5   /**< 单轴采样次数 */
#define TP_LOST_VAL     1   /**< 排序后丢弃的极值个数 (最高/最低各 1) */
#define TP_ERR_RANGE    100 /**< 双采样校验允许的最大偏差 (电阻屏抖动较大, 不宜过紧) */

/**
 * 有效坐标最小值阈值: 读数低于此值视为无效 (未按下/通信异常).
 * XPT2046 有效坐标远大于 100, 此阈值不会误杀正常读数
 */
#define TP_READ_MIN     100

/* ========================================================================= */
/*  PEN 中断 (可选)                                                           */
/* ========================================================================= */
/**
 * PEN 中断开关:
 *   1 = EXTI 事件驱动 (无按压时不轮询, 省 CPU, 为低功耗唤醒预留)
 *   0 = 纯轮询 (原行为)
 * @note 修改 PEN 引脚所在端口/引脚时, 需同步更新 TP_PEN_EXTI_IRQn
 */
#define TP_PEN_INT_ENABLE   1
/** PEN 引脚 EXTI 中断号 (PC5=EXTI 线5 → EXTI9_5_IRQn) */
#define TP_PEN_EXTI_IRQn    EXTI9_5_IRQn
/** PEN 中断抢占优先级 (数值越小优先级越高) */
#define TP_PEN_EXTI_PRIO    3

/* ========================================================================= */
/*  手势识别参数                                                              */
/* ========================================================================= */
/**
 * 最短按压确认时间 (ms): 按下后需持续按住超过此时间才认定为有效按压.
 * 防止误触/抖动: 太短(如误碰、噪声尖峰)的按下会被忽略, 不产生单击
 */
#define TOUCH_MIN_PRESS_TIME    30
/**
 * 释放消抖时间 (ms): 松开后需保持松开超过此时间才确认释放.
 * PEN 在松开瞬间的弹跳 (短暂低电平) 会被合并为同一次按压, 避免一次点击
 * 被拆成多次
 */
#define TOUCH_RELEASE_DEBOUNCE  20
/** 长按阈值 (ms): 按下时间超过此值且未滑动, 判定为长按 */
#define TOUCH_LONG_PRESS_TIME   500
/** 滑动判定阈值 (像素): 按下后移动距离超过此值判定为滑动 (移动优先于长按) */
#define TOUCH_SWIPE_THRESHOLD   20

#endif /* __TOUCH_CONF_H */
